package com.cramit.domain.stt;

/**
 * 페이지 매핑용 프롬프트. CRAMIT-TEST prompts/의 terms_llm, postprocess_audio + postprocess_rule_diff, match를 옮겼다.
 * TEST는 PDF에서 뽑은 텍스트를 넣었지만 여기서는 PDF를 그대로 첨부한다.
 */
final class PageMappingPrompts {

    private PageMappingPrompts() {
    }

    static final String TERMS = """
            첨부한 PDF는 한 강의의 슬라이드 덱이다.

            이 강의의 음성 인식(STT) 전사문을 교정할 때 쓸 **용어 목록**을 만들어라.
            목적은 강의자가 말할 전문용어·고유명사의 표기를 맞추는 것이다.

            넣을 것:
            - 슬라이드의 전공용어, 정리·기법·자료구조 이름, 고유명사, 제품·모델명, 약어

            빼야 할 것:
            - 강의자가 소리 내어 읽지 않는 것: 수식 자체, 코드 조각
            - 일반 영어 구(`there exist constants`, `total weight`, `big enough`)
            - 슬라이드 상투어(Example, Case, Idea, Lecture, Summary)

            지켜야 할 규칙:
            - **슬라이드에 실제로 적힌 표현만 쓴다.** 네가 아는 이 분야 용어를 보태지 마라.
            - 표기는 슬라이드에 적힌 그대로 옮긴다. 대소문자·하이픈을 바꾸지 마라.
            - 한 페이지에서 8개를 넘기지 마라. 많이 넣는 게 좋은 게 아니다.
            - 같은 용어는 한 번만 넣는다.
            """;

    private static final String CORRECTION = """
            한국어 강의 녹음의 일부와, 그 구간을 음성인식(STT)한 전사문이다.
            STT 가 뭉갠 곳이 있다. **오디오를 듣고, 실제 발화대로 고쳐라.**

            ## 고칠 것
            - 실제 발화와 다른 말이 적힌 구간. 들리는 대로 고쳐라.
            - 영어 전문용어가 엉뚱한 한국어로 적힌 것. 예: `비고` → `Big-O`, `랩핑크스` → `recursion tree`
            - 한글 음차로 적힌 전문용어는 영문 표기로 바꾼다. 예: `오메가` → `Omega`

            ## 절대 하지 말 것
            - **구간을 합치거나 나누지 마라.** 각 구간의 text 는 그 구간의 시각 범위에서 들리는 말만 담는다.
              옆 구간에서 들리는 말을 끌어오지 마라.
            - 문장을 다듬지 마라. 말더듬·반복·구어체·비문을 **들리는 그대로** 둬라.
              ("이것만 이것만" 을 "이것만" 으로 줄이지 마라)
            - **안 들리는 자리를 문맥으로 채우지 마라.** 잡음·묵음·겹쳐 말하기로 못 알아듣겠으면
              원문을 그대로 둬라. 지어내는 것이 가장 나쁘다.
            - 요약하지 마라. 내용을 보태지 마라.
            - 아래 용어 목록에 없는 영어 용어를 만들어 넣지 마라.

            ## 판단이 서지 않으면
            원문 그대로 둬라. 고치는 것보다 두는 것이 낫다.

            ## 이 강의의 용어 목록 (표기 통일용 — 발화되지 않은 용어를 끼워 넣는 근거가 아니다)
            %s

            ## 오디오
            이 오디오는 강의의 %d 초 ~ %d 초 구간이다.
            아래 각 구간에 붙은 괄호 안 시각은 **이 오디오 조각의 맨 앞을 0초로 삼은** 상대 시각이다.

            ## 전사문 구간
            %s

            ## 출력 규칙 — 고친 구간만
            **실제로 고친 구간만** 돌려줘라. 원문 그대로 두는 구간은 출력에서 **빼라**.
            - text 는 그 구간의 **완성된 전체 문장**이다. 바뀐 낱말만 보내지 마라.
            - id 는 위 대괄호 안의 번호를 그대로 쓴다. 위에 없는 번호를 만들지 마라.
            - 고칠 것이 하나도 없으면 빈 목록을 돌려줘라.
            """;

    // TEST match.txt에서 "강의 전후 잡담은 빼라"만 뺐다. 저장할 때 0초~끝을 빈틈없이 채운다.
    private static final String MAPPING = """
            너는 강의 녹음과 강의 슬라이드를 정렬한다.

            (1) 첨부한 PDF가 강의 슬라이드이고, (2) 아래에 시각이 붙은 강의 전사문이 있다.
            전사문의 각 시점에 강의자가 어느 페이지를 설명하고 있었는지 판정해
            페이지별 시간 구간을 만들어라. 페이지 번호는 PDF의 페이지 순서(1부터)다.

            ## 두 축을 구분해라 — 여기가 핵심이다

            **시간축은 예외 없이 단조 증가한다.**
            - 모든 구간은 startSec < endSec 이다. 끝이 시작보다 앞서는 구간은 있을 수 없다.
            - 구간을 시간 순으로 나열해라. 다음 구간의 startSec 는 앞 구간의 endSec 이상이다.
            - 구간끼리 겹치지 않는다. 한 시점은 한 구간에만 속한다.

            **페이지 번호는 단조가 아니다.**
            - 대체로 커지지만, 질의응답으로 앞 페이지로 되돌아가거나 뒤로 건너뛸 수 있다.
            - 되돌아간다는 것은 **시간은 계속 흐르는데 page 만 작아진다**는 뜻이다.
              시간을 되돌리는 것이 아니다.
            - 같은 페이지가 시간대를 달리해 여러 번 나올 수 있다. 그럴 땐 구간을 따로 만든다.

            ## 페이지를 다 쓰지 마라

            한 수업이 슬라이드 전체를 다루는 경우는 드물다.
            - **강의에서 실제로 다룬 페이지만 넣어라.** 언급되지 않은 페이지는 결과에서 그냥 빠진다.
            - 남는 페이지를 채우려고 억지로 시간을 나누지 마라. 빠진 페이지가 많아도 그게 정상이다.
            - 근거는 전사문이다. 슬라이드에만 있고 전사문에 흔적이 없으면 그 페이지는 안 다룬 것이다.

            ## 나머지 규칙

            - 각 구간에 page, startSec, endSec, title(그 구간을 한국어 한 줄로 요약)을 붙인다.
            - 시간은 전사문에 적힌 초 값을 그대로 쓴다. 새로 계산하지 마라.
            - 슬라이드를 띄워 둔 채 잡담·공지를 하는 구간은 직전 페이지 구간에 이어 붙인다.
            - 첫 구간과 마지막 구간 사이에는 시간상 빈틈이 없어야 한다.
            - 시간을 빈틈없이 덮으라는 것이 페이지를 다 쓰라는 뜻은 아니다.

            ## 전사문 (초 단위 시각)
            %s
            """;

    static String correction(String terms, int windowFrom, int windowTo, String segments) {
        return CORRECTION.formatted(terms, windowFrom, windowTo, segments);
    }

    static String mapping(String transcriptLines) {
        return MAPPING.formatted(transcriptLines);
    }
}
